import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const packagesRoot = join(packageRoot, "..");
const outputPath = join(packageRoot, "src", "index.ts");

// Maps a CEM attribute type string to a TypeScript type. Primitives and simple
// string-literal unions get their exact type; anything else falls back to the
// permissive LoomiAttributeValue union so the generated file never needs
// additional imports for component-specific types.
const cemTypeToTs = (text) => {
  if (!text) return "LoomiAttributeValue";
  const t = text.trim();
  if (t === "boolean") return "boolean";
  if (t === "string") return "string";
  if (t === "number") return "number";
  if (/^"[^"]*"(\s*\|\s*"[^"]*")*$/.test(t)) return t;
  return "LoomiAttributeValue";
};

const componentDefinitions = [];

for (const packageName of await readdir(packagesRoot)) {
  const manifestPath = join(packagesRoot, packageName, "custom-elements.json");
  let manifest;
  try {
    manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") continue;
    throw error;
  }

  for (const module of manifest.modules ?? []) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.customElement || !declaration.tagName?.startsWith("loomi-")) continue;
      componentDefinitions.push({
        tagName: declaration.tagName,
        attributes: (declaration.attributes ?? [])
          .filter((attr) => typeof attr.name === "string" && attr.name.includes("-"))
          .map((attr) => ({ name: attr.name, type: cemTypeToTs(attr.type?.text) })),
      });
    }
  }
}

componentDefinitions.sort((a, b) => a.tagName.localeCompare(b.tagName));

const duplicate = componentDefinitions.find(
  (definition, index) => definition.tagName === componentDefinitions[index - 1]?.tagName,
);
if (duplicate) throw new Error(`Duplicate custom element manifest entry: ${duplicate.tagName}`);

const typeName = (tagName) =>
  `${tagName
    .split("-")
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("")}Attributes`;

const attributeTypes = componentDefinitions
  .map(({ tagName, attributes }) => {
    const seen = new Map();
    for (const { name, type } of attributes) {
      if (!seen.has(name)) seen.set(name, type);
    }
    const entries = [...seen.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, type]) => `  ${JSON.stringify(name)}?: ${type};`)
      .join("\n");
    return `interface ${typeName(tagName)} {\n${entries}\n}`;
  })
  .join("\n\n");

const intrinsicMembers = componentDefinitions
  .map(
    ({ tagName }) =>
      `      ${JSON.stringify(tagName)}: LoomiReactProps<HTMLElementTagNameMap[${JSON.stringify(tagName)}], ${typeName(tagName)}>;`,
  )
  .join("\n");

const source = `// Generated by ${relative(packageRoot, fileURLToPath(import.meta.url))}. Do not edit directly.
import type { HTMLAttributes, RefAttributes } from "react";
import type { LoomiElement } from "@loomidev/core";
import type {} from "@loomidev/components";

type LoomiAttributeValue = string | number | boolean | undefined;
type LoomiOwnPropertyNames<T extends LoomiElement> = {
  [K in Exclude<keyof T, keyof LoomiElement>]: T[K] extends (...args: never[]) => unknown
    ? never
    : K;
}[Exclude<keyof T, keyof LoomiElement>];
type LoomiOwnProperties<T extends LoomiElement> = Partial<Pick<T, LoomiOwnPropertyNames<T>>>;

export type LoomiReactProps<
  T extends LoomiElement,
  TAttributes extends object = Record<never, never>,
> = Omit<HTMLAttributes<T>, keyof LoomiOwnProperties<T> | keyof TAttributes> &
  RefAttributes<T> &
  LoomiOwnProperties<T> &
  TAttributes & {
    name?: string;
  };

${attributeTypes}

declare module "react" {
  namespace JSX {
    interface IntrinsicElements {
${intrinsicMembers}
    }
  }
}

declare global {
  namespace JSX {
    interface IntrinsicElements {
${intrinsicMembers}
    }
  }
}
`;

const prettierConfig = (await resolveConfig(outputPath)) ?? {};
await writeFile(outputPath, await format(source, { ...prettierConfig, parser: "typescript" }));
console.log(
  `[react-types] Generated JSX declarations for ${componentDefinitions.length} elements.`,
);
