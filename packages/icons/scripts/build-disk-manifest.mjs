// Scans src/svg/<source>/<type>/*.svg and emits one opt-in entry module per source,
// src/generated/sources/<source>.ts, published as `@loomidev/icons/<source>`. Importing
// it registers that source's name list and its lazy per-type loaders with
// disk-icons.ts; a source nobody imports costs nothing, not even its names, and its
// thousands of per-icon modules never enter the consumer's module graph.
//
// Introducing a brand new disk-based source is: drop its files under
// src/svg/<source>/<type>/, add it to LoomiDiskIconSource in disk-icons.ts and to
// package.json "exports"/"sideEffects", rebuild.

import { readdirSync, writeFileSync, mkdirSync, rmSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(root, "..");
const svgRoot = join(pkgRoot, "src", "svg");
const outDir = join(pkgRoot, "src", "generated");
const sourcesDir = join(outDir, "sources");

const isDir = (path) => statSync(path).isDirectory();
const iconName = (file) => file.replace(/\.svg$/, "");

const sources = readdirSync(svgRoot).filter((entry) => isDir(join(svgRoot, entry)));

rmSync(join(outDir, "disk-manifest.ts"), { force: true });
rmSync(join(outDir, "disk-loaders.ts"), { force: true });
rmSync(sourcesDir, { recursive: true, force: true });
mkdirSync(sourcesDir, { recursive: true });

let total = 0;
for (const source of sources.sort()) {
  const sourceDir = join(svgRoot, source);
  const types = readdirSync(sourceDir)
    .filter((entry) => isDir(join(sourceDir, entry)))
    .sort();

  const sets = types.map((type) => {
    const names = readdirSync(join(sourceDir, type))
      .filter((file) => file.endsWith(".svg"))
      .map(iconName)
      .sort();
    total += names.length;
    return `  ${JSON.stringify(type)}: {
    names: ${JSON.stringify(names)},
    load: () => import(${JSON.stringify(`../../icons/${source}/${type}/index.js`)}),
  },`;
  });

  writeFileSync(
    join(sourcesDir, `${source}.ts`),
    `// AUTO-GENERATED by scripts/build-disk-manifest.mjs — do not edit by hand.
// Regenerate with: pnpm --filter @loomidev/icons build
//
// Side-effect entry: \`import "@loomidev/icons/${source}";\` makes source="${source}" render.
import { registerLoomiDiskIconSource } from "../../disk-icons.js";

registerLoomiDiskIconSource(${JSON.stringify(source)}, {
${sets.join("\n")}
});
`,
  );
}

console.log(`Generated ${sources.length} disk icon source entries — ${total} icons.`);
