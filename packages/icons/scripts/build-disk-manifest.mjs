// Scans src/svg/<source>/<type>/*.svg and emits src/generated/disk-manifest.ts
// — the list of names disk-icons.ts validates against before ever building a
// URL or fetching. Runs on every `pnpm build` (cheap: it's just filenames).
//
// Introducing a brand new disk-based source is therefore just: drop its files
// under src/svg/<source>/<type>/, rebuild. No edits needed here.

import { readdirSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(root, "..");
const svgRoot = join(pkgRoot, "src", "svg");
const outDir = join(pkgRoot, "src", "generated");
const outFile = join(outDir, "disk-manifest.ts");

const isDir = (path) => statSync(path).isDirectory();
const iconName = (file) => file.replace(/\.svg$/, "");

const sources = readdirSync(svgRoot).filter((entry) => isDir(join(svgRoot, entry)));

const manifest = {};
let total = 0;
for (const source of sources.sort()) {
  const sourceDir = join(svgRoot, source);
  const types = readdirSync(sourceDir).filter((entry) => isDir(join(sourceDir, entry)));

  manifest[source] = {};
  for (const type of types.sort()) {
    const names = readdirSync(join(sourceDir, type))
      .filter((file) => file.endsWith(".svg"))
      .map(iconName)
      .sort();
    manifest[source][type] = names;
    total += names.length;
  }
}

const body = JSON.stringify(manifest, null, 2);

const output = `// AUTO-GENERATED by scripts/build-disk-manifest.mjs — do not edit by hand.
// Regenerate with: pnpm --filter @loomidev/icons build

/** Registered icon names per disk-based source and type. */
export const DISK_ICON_NAMES = ${body} as const;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, output);
console.log(`Generated disk-manifest.ts — ${total} icons across ${sources.length} source(s).`);
