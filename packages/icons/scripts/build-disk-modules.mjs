// Emits bundler-native ES modules for every disk-based icon, alongside the raw
// .svg files that copy-svg-assets.mjs ships.
//
// Why both: a bundler emits JS, never an arbitrary asset folder, so the raw
// dist/svg/ files only resolve when the package keeps its real module URL (a
// CDN, an import map, or a base path set via setLoomiIconBasePath). Bundled
// apps get these modules instead — every import specifier below is a string
// literal, so webpack/Vite/Rollup/esbuild all trace and code-split them
// without any asset-copying step in the consuming app.
//
// Layout, per source/type:
//   dist/icons/<source>/<type>/<name>.js  -> export default "<inner markup>"
//   dist/icons/<source>/<type>/index.js   -> { loaders: { name: () => import(...) } }
//   src/icons/<source>/<type>/index.d.ts  -> type stub so tsc can resolve the
//                                            dynamic imports in disk-loaders.ts
//
// The per-icon modules are written straight to dist/: tsc never reads them
// (only the generated index.js references them), so routing 3,859 files
// through the compiler would be pure cost.

import { readdirSync, writeFileSync, mkdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(root, "..");
const svgRoot = join(pkgRoot, "src", "svg");
const distIcons = join(pkgRoot, "dist", "icons");
const srcIcons = join(pkgRoot, "src", "icons");
const generatedDir = join(pkgRoot, "src", "generated");

const isDir = (path) => statSync(path).isDirectory();
const iconName = (file) => file.replace(/\.svg$/, "");

// Identical to the extraction disk-icons.ts applies to a fetched .svg, so a
// module and a fetch of the same icon yield byte-identical inner markup.
const innerMarkup = (raw) =>
  raw
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim();

const BANNER = "// AUTO-GENERATED by scripts/build-disk-modules.mjs — do not edit by hand.";

rmSync(distIcons, { recursive: true, force: true });
rmSync(srcIcons, { recursive: true, force: true });

const sets = [];
let total = 0;

for (const source of readdirSync(svgRoot)
  .filter((e) => isDir(join(svgRoot, e)))
  .sort()) {
  const sourceDir = join(svgRoot, source);
  for (const type of readdirSync(sourceDir)
    .filter((e) => isDir(join(sourceDir, e)))
    .sort()) {
    const typeDir = join(sourceDir, type);
    const outDir = join(distIcons, source, type);
    mkdirSync(outDir, { recursive: true });

    const names = readdirSync(typeDir)
      .filter((f) => f.endsWith(".svg"))
      .map(iconName)
      .sort();

    for (const name of names) {
      const raw = readFileSync(join(typeDir, `${name}.svg`), "utf8");
      writeFileSync(
        join(outDir, `${name}.js`),
        `${BANNER}\nexport default ${JSON.stringify(innerMarkup(raw))};\n`,
      );
    }

    const entries = names
      .map((name) => `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`./${name}.js`)}),`)
      .join("\n");
    writeFileSync(
      join(outDir, "index.js"),
      `${BANNER}\n// Every specifier is a literal so bundlers can trace and split each icon.\nexport const loaders = {\n${entries}\n};\n`,
    );

    const stubDir = join(srcIcons, source, type);
    mkdirSync(stubDir, { recursive: true });
    writeFileSync(
      join(stubDir, "index.d.ts"),
      `${BANNER}\nexport declare const loaders: Record<string, () => Promise<{ default: string }>>;\n`,
    );

    sets.push({ source, type, count: names.length });
    total += names.length;
  }
}

// Shared types for consumers importing a single icon module by subpath:
//   import home from "@loomidev/icons/icons/iconsax/outline/home.js";
writeFileSync(
  join(distIcons, "icon-module.d.ts"),
  `${BANNER}\n/** Inner SVG markup for one icon, ready to drop inside an <svg> element. */\ndeclare const markup: string;\nexport default markup;\n`,
);

const loaderEntries = sets
  .map(
    ({ source, type }) =>
      `  ${JSON.stringify(`${source}/${type}`)}: () => import(${JSON.stringify(`../icons/${source}/${type}/index.js`)}),`,
  )
  .join("\n");

mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  join(generatedDir, "disk-loaders.ts"),
  `${BANNER}
// Regenerate with: pnpm --filter @loomidev/icons build

/** One lazily-imported icon set: name -> loader for that icon's module. */
export interface DiskIconSetModule {
  loaders: Record<string, () => Promise<{ default: string }>>;
}

/** Keyed \`<source>/<type>\`. Static literal specifiers keep these traceable. */
export const DISK_ICON_SET_LOADERS: Record<string, () => Promise<DiskIconSetModule>> = {
${loaderEntries}
};
`,
);

const summary = sets.map(({ source, type, count }) => `${source}/${type} (${count})`).join(", ");
console.log(`Generated ${total} icon modules across ${sets.length} set(s): ${summary}`);
