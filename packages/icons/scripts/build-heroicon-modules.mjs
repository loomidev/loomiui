// Emits one ES module per Heroicon, from data/heroicons.json (see generate-heroicons.mjs).
//
// Why per icon: a component that renders `icon="bell"` should cost a consumer that one
// icon, not the whole 240+240 set. The registry in src/heroicons.ts resolves names
// through the literal-specifier loader map below, so every bundler code-splits each icon
// into its own tiny lazy chunk; a component's own chrome icons (a clear button's
// x-circle) import their module directly and ship inline.
//
// Layout:
//   dist/heroicons/<variant>/<name>.js   -> export default svg`<inner markup>`
//   dist/heroicons/<variant>/all.js      -> export default { name: icon, … } (eager, opt-in)
//   dist/heroicons/loaders.js            -> { outline: { name: () => import(…) }, solid: … }
//   dist/heroicons/names.js              -> the name list, for synchronous hasLoomiIcon()
//   dist/heroicons/icon-module.d.ts      -> shared type for the per-icon subpath export
//   src/heroicons/**/*.d.ts              -> type stubs so tsc resolves the files above
//
// Like build-disk-modules.mjs, the modules go straight to dist/: routing 480 generated
// files through tsc would be pure cost.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(pkgRoot, "data", "heroicons.json"), "utf8"));
const distDir = join(pkgRoot, "dist", "heroicons");
const stubDir = join(pkgRoot, "src", "heroicons");

const BANNER = "// AUTO-GENERATED by scripts/build-heroicon-modules.mjs — do not edit by hand.";
const variants = Object.keys(data).sort();

rmSync(distDir, { recursive: true, force: true });
rmSync(stubDir, { recursive: true, force: true });

// Template literal content: markup never contains backticks or `${`, but escape anyway.
const asTemplate = (markup) => markup.replace(/[`\\]/g, "\\$&").replace(/\$\{/g, "\\${");

let total = 0;
for (const variant of variants) {
  const dir = join(distDir, variant);
  mkdirSync(dir, { recursive: true });
  const names = Object.keys(data[variant]).sort();

  for (const name of names) {
    writeFileSync(
      join(dir, `${name}.js`),
      `${BANNER}\nimport { svg } from "lit";\nexport default svg\`${asTemplate(data[variant][name])}\`;\n`,
    );
  }

  writeFileSync(
    join(dir, "all.js"),
    `${BANNER}\n// Every ${variant} icon, eagerly. Imported by @loomidev/icons/all only.\n${names
      .map((name, i) => `import i${i} from ${JSON.stringify(`./${name}.js`)};`)
      .join("\n")}\nexport default {\n${names
      .map((name, i) => `  ${JSON.stringify(name)}: i${i},`)
      .join("\n")}\n};\n`,
  );

  mkdirSync(join(stubDir, variant), { recursive: true });
  writeFileSync(
    join(stubDir, variant, "all.d.ts"),
    `${BANNER}\nimport type { SVGTemplateResult } from "lit";\ndeclare const icons: Record<string, SVGTemplateResult>;\nexport default icons;\n`,
  );
  total += names.length;
}

writeFileSync(
  join(distDir, "loaders.js"),
  `${BANNER}\n// Every specifier is a literal so bundlers can trace and split each icon.\nexport const HEROICON_LOADERS = {\n${variants
    .map(
      (variant) =>
        `  ${variant}: {\n${Object.keys(data[variant])
          .sort()
          .map(
            (name) =>
              `    ${JSON.stringify(name)}: () => import(${JSON.stringify(`./${variant}/${name}.js`)}),`,
          )
          .join("\n")}\n  },`,
    )
    .join("\n")}\n};\n`,
);

// Names only, space-joined: what hasLoomiIcon() needs synchronously, at ~1 KB gzipped
// instead of the ~4 KB loader map, which the registry imports lazily on first load.
const joined = Object.fromEntries(variants.map((v) => [v, Object.keys(data[v]).sort().join(" ")]));
const shared = variants.every((v) => joined[v] === joined[variants[0]]);
writeFileSync(
  join(distDir, "names.js"),
  shared
    ? `${BANNER}\nconst names = ${JSON.stringify(joined[variants[0]])};\nexport const HEROICON_NAMES = { ${variants.map((v) => `${v}: names`).join(", ")} };\n`
    : `${BANNER}\nexport const HEROICON_NAMES = ${JSON.stringify(joined)};\n`,
);
writeFileSync(
  join(stubDir, "names.d.ts"),
  `${BANNER}\n/** Space-separated icon names per variant. */\nexport declare const HEROICON_NAMES: Record<"outline" | "solid", string>;\n`,
);

const iconModuleType = `${BANNER}\nimport type { SVGTemplateResult } from "lit";\n/** One Heroicon's inner SVG, ready to drop inside an <svg> element. */\ndeclare const icon: SVGTemplateResult;\nexport default icon;\n`;
writeFileSync(join(distDir, "icon-module.d.ts"), iconModuleType);
writeFileSync(
  join(stubDir, "loaders.d.ts"),
  `${BANNER}\nimport type { SVGTemplateResult } from "lit";\nexport declare const HEROICON_LOADERS: Record<\n  "outline" | "solid",\n  Record<string, () => Promise<{ default: SVGTemplateResult }>>\n>;\n`,
);

console.log(`Generated ${total} Heroicon modules (${variants.join(", ")}).`);
